/*
 * build193 - normal floor-boss signature equipment, batches 1-5.
 *
 * Every boss owns three independent Mythic pieces. They intentionally have no
 * series id or set bonus: each piece should be worth considering on its own.
 * Acquisition is wired in the final reward-system batch; these definitions are
 * already complete so old/new item instances can be normalized safely.
 */

const ART_ROOT="./assets/ui/equipment/floor-boss";

function piece(floor,slot,name,stats,effect,{subslot=null}={}){
 return Object.freeze({
  id:`floor-boss-${floor}-${slot}`,
  slot,subslot,name,rarity:"神話",
  stats:Object.freeze({...stats}),
  effect:Object.freeze({...effect,fixedEffects:Object.freeze({...effect.fixedEffects})}),
  visualAsset:`${ART_ROOT}/${String(floor).padStart(3,"0")}/${slot}.png`,
  standalone:true
 });
}

function set(floor,weaponName,armorName,armorStats,armorEffect,accessoryName,accessoryStats,accessoryEffect){
 return Object.freeze({
  floor,
  weapon:Object.freeze({
   id:`floor-boss-${floor}-weapon`,slot:"weapon",name:weaponName,rarity:"神話",
   visualAsset:`${ART_ROOT}/${String(floor).padStart(3,"0")}/weapon.png`,standalone:true
  }),
  armor:piece(floor,"armor",armorName,armorStats,armorEffect,{subslot:"armorBody"}),
  accessory:piece(floor,"accessory",accessoryName,accessoryStats,accessoryEffect,{subslot:"accessoryNeck"})
 });
}

